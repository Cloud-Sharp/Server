using CloudSharp.Core.Domain.Users;
using CloudSharp.Infrastructure.Persistence.DbContext;
using CloudSharp.Infrastructure.Persistence.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Npgsql.EntityFrameworkCore.PostgreSQL.Metadata;
using NUnit.Framework;

namespace CloudSharp.Infrastructure.Tests.Persistence.Configurations;

/// <summary>
/// <see cref="UserEntity"/> EF 모델 메타데이터 검증. 실제 PostgreSQL 반영은
/// <see cref="CloudSharp.Infrastructure.Tests.Persistence.Entities.UserEntityPersistenceTests"/>가 담당한다.
/// </summary>
[TestFixture]
public sealed class UserConfigurationTests
{
    private ServiceProvider provider = null!;
    private IEntityType entityType = null!;
    private string createScript = null!;

    [OneTimeSetUp]
    public void OneTimeSetUp()
    {
        var configuration = new ConfigurationBuilder()
            .AddInMemoryCollection(new Dictionary<string, string?>
            {
                ["ConnectionStrings:PostgreSql"] =
                    "Host=localhost;Database=cloudsharp_user_model_tests;Username=postgres;Password=postgres",
            })
            .Build();
        var services = new ServiceCollection();
        services.AddPostgreSqlPersistence(configuration);
        provider = services.BuildServiceProvider();
        var context = provider.GetRequiredService<AppDbContext>();

        entityType = context.GetService<IDesignTimeModel>().Model.FindEntityType(typeof(UserEntity))
            ?? throw new InvalidOperationException("UserEntity is not mapped.");
        createScript = context.Database.GenerateCreateScript();
    }

    [OneTimeTearDown]
    public void OneTimeTearDown()
    {
        provider.Dispose();
    }

    [Test]
    public void Users_WhenModelIsBuilt_ShouldExposeSixteenSnakeCaseColumns()
    {
        var columns = entityType.GetProperties()
            .Select(property => property.GetColumnName())
            .Order()
            .ToArray();

        Assert.That(columns, Is.EqualTo(new[]
        {
            "created_at", "deleted_at", "display_name", "email", "id", "normalized_email",
            "normalized_user_name", "password_hash", "public_id", "security_version", "status",
            "suspended_at", "system_role", "updated_at", "user_name", "version",
        }));
    }

    [TestCaseSource(nameof(ColumnStoreTypeCases))]
    public void Column_WhenModelIsBuilt_ShouldHaveDocumentedStoreType(string columnName, string expectedStoreType)
    {
        Assert.That(Column(columnName).GetColumnType(), Is.EqualTo(expectedStoreType));
    }

    [TestCaseSource(nameof(RequiredColumnCases))]
    public void Column_WhenModelIsBuilt_ShouldBeRequired(string columnName)
    {
        Assert.That(Column(columnName).IsNullable, Is.False);
    }

    [TestCaseSource(nameof(OptionalColumnCases))]
    public void Column_WhenModelIsBuilt_ShouldAllowNull(string columnName)
    {
        Assert.That(Column(columnName).IsNullable, Is.True);
    }

    [Test]
    public void Id_WhenModelIsBuilt_ShouldBeGeneratedByDefaultIdentity()
    {
        var id = Column("id");

        Assert.Multiple(() =>
        {
            Assert.That(id.GetValueGenerationStrategy(), Is.EqualTo(NpgsqlValueGenerationStrategy.IdentityByDefaultColumn));
            Assert.That(id.ValueGenerated, Is.EqualTo(ValueGenerated.OnAdd));
            Assert.That(createScript, Does.Contain("id bigint GENERATED BY DEFAULT AS IDENTITY"));
        });
    }

    [Test]
    public void DefaultedColumns_WhenModelIsBuilt_ShouldHaveDocumentedDefaultsAndPersistSuppliedValues()
    {
        var systemRole = Column("system_role");
        var status = Column("status");
        var securityVersion = Column("security_version");
        var version = Column("version");

        Assert.Multiple(() =>
        {
            Assert.That(systemRole.GetDefaultValue(), Is.EqualTo(SystemRole.User));
            Assert.That(status.GetDefaultValue(), Is.EqualTo(UserStatus.Active));
            Assert.That(securityVersion.GetDefaultValue(), Is.EqualTo(1L));
            Assert.That(version.GetDefaultValue(), Is.EqualTo(1L));
            Assert.That(systemRole.ValueGenerated, Is.EqualTo(ValueGenerated.Never));
            Assert.That(status.ValueGenerated, Is.EqualTo(ValueGenerated.Never));
            Assert.That(securityVersion.ValueGenerated, Is.EqualTo(ValueGenerated.Never));
            Assert.That(version.ValueGenerated, Is.EqualTo(ValueGenerated.Never));
        });
    }

    [Test]
    public void Version_WhenModelIsBuilt_ShouldBeConcurrencyToken()
    {
        Assert.That(Column("version").IsConcurrencyToken, Is.True);
    }

    [Test]
    public void CreateScript_WhenModelIsBuilt_ShouldNotConfigureDatabaseDefaultsOnPublicIdAndTimestamps()
    {
        Assert.Multiple(() =>
        {
            Assert.That(createScript, Does.Contain("public_id uuid NOT NULL"));
            Assert.That(createScript, Does.Contain("created_at timestamptz NOT NULL"));
            Assert.That(createScript, Does.Contain("updated_at timestamptz NOT NULL"));
            Assert.That(createScript, Does.Not.Contain("public_id uuid NOT NULL DEFAULT"));
            Assert.That(createScript, Does.Not.Contain("created_at timestamptz NOT NULL DEFAULT"));
            Assert.That(createScript, Does.Not.Contain("updated_at timestamptz NOT NULL DEFAULT"));
        });
    }

    [Test]
    public void PrimaryKey_WhenModelIsBuilt_ShouldBeNamedPkUsersOnId()
    {
        var primaryKey = entityType.FindPrimaryKey();

        Assert.Multiple(() =>
        {
            Assert.That(primaryKey, Is.Not.Null);
            Assert.That(primaryKey!.GetName(), Is.EqualTo("pk_users"));
            Assert.That(
                primaryKey!.Properties.Select(property => property.GetColumnName()),
                Is.EqualTo(new[] { "id" }));
        });
    }

    [Test]
    public void UniqueIndexes_WhenModelIsBuilt_ShouldHaveDocumentedNamesAndFilter()
    {
        var indexes = entityType.GetIndexes().ToList();

        var publicId = indexes.Single(index => index.GetDatabaseName() == "ux_users_public_id");
        var normalizedEmail = indexes.Single(index => index.GetDatabaseName() == "ux_users_normalized_email");
        var normalizedUserName = indexes.Single(index => index.GetDatabaseName() == "ux_users_normalized_user_name");

        Assert.Multiple(() =>
        {
            Assert.That(publicId.IsUnique, Is.True);
            Assert.That(normalizedEmail.IsUnique, Is.True);
            Assert.That(normalizedUserName.IsUnique, Is.True);
            Assert.That(normalizedUserName.GetFilter(), Is.EqualTo("normalized_user_name IS NOT NULL"));
        });
    }

    [Test]
    public void CreateScript_WhenModelIsBuilt_ShouldCreateEnumTypesWithUppercaseLabels()
    {
        Assert.Multiple(() =>
        {
            Assert.That(createScript, Does.Contain("CREATE TYPE system_role_t AS ENUM ('SYSTEM_ADMIN', 'USER')"));
            Assert.That(createScript, Does.Contain("CREATE TYPE user_status_t AS ENUM ('ACTIVE', 'DELETED', 'SUSPENDED')"));
        });
    }

    [Test]
    public void CreateScript_WhenModelIsBuilt_ShouldRenderIndexesWithDocumentedSortOrders()
    {
        Assert.Multiple(() =>
        {
            Assert.That(createScript, Does.Contain("CREATE UNIQUE INDEX ux_users_public_id ON users (public_id)"));
            Assert.That(createScript, Does.Contain("CREATE UNIQUE INDEX ux_users_normalized_email ON users (normalized_email)"));
            Assert.That(createScript, Does.Contain(
                "CREATE UNIQUE INDEX ux_users_normalized_user_name ON users (normalized_user_name) WHERE normalized_user_name IS NOT NULL"));
            Assert.That(createScript, Does.Contain("CREATE INDEX idx_users_status_created_at ON users (status, created_at DESC)"));
            Assert.That(createScript, Does.Contain("CREATE INDEX idx_users_created_at_id ON users (created_at DESC, id DESC)"));
        });
    }

    [Test]
    public void CheckConstraints_WhenModelIsBuilt_ShouldHaveExactlyTheDocumentedNames()
    {
        var names = entityType.GetCheckConstraints()
            .Select(constraint => constraint.Name)
            .Order()
            .ToArray();

        Assert.That(names, Is.EqualTo(new[]
        {
            "chk_users_email_not_blank", "chk_users_security_version_positive",
            "chk_users_status_timestamps", "chk_users_user_name_pair", "chk_users_version_positive",
        }));
    }

    [TestCaseSource(nameof(CheckConstraintCases))]
    public void CheckConstraint_WhenModelIsBuilt_ShouldMatchDocumentedDefinition(string name, string sql)
    {
        var constraint = entityType.GetCheckConstraints()
            .Single(checkConstraint => checkConstraint.Name == name);

        Assert.That(constraint.Sql, Is.EqualTo(sql));
    }

    private IReadOnlyProperty Column(string columnName)
        => entityType.GetProperties().Single(property => property.GetColumnName() == columnName);

    public static IEnumerable<TestCaseData> ColumnStoreTypeCases()
    {
        yield return new TestCaseData("id", "bigint");
        yield return new TestCaseData("public_id", "uuid");
        yield return new TestCaseData("email", "character varying(320)");
        yield return new TestCaseData("normalized_email", "character varying(320)");
        yield return new TestCaseData("user_name", "character varying(30)");
        yield return new TestCaseData("normalized_user_name", "character varying(30)");
        yield return new TestCaseData("display_name", "character varying(100)");
        yield return new TestCaseData("password_hash", "character varying(512)");
        yield return new TestCaseData("system_role", "system_role_t");
        yield return new TestCaseData("status", "user_status_t");
        yield return new TestCaseData("security_version", "bigint");
        yield return new TestCaseData("version", "bigint");
        yield return new TestCaseData("created_at", "timestamptz");
        yield return new TestCaseData("updated_at", "timestamptz");
        yield return new TestCaseData("suspended_at", "timestamptz");
        yield return new TestCaseData("deleted_at", "timestamptz");
    }

    public static IEnumerable<TestCaseData> RequiredColumnCases()
    {
        foreach (var columnName in new[]
                 {
                     "id", "public_id", "email", "normalized_email", "password_hash",
                     "system_role", "status", "security_version", "version", "created_at", "updated_at",
                 })
        {
            yield return new TestCaseData(columnName);
        }
    }

    public static IEnumerable<TestCaseData> OptionalColumnCases()
    {
        foreach (var columnName in new[]
                 {
                     "user_name", "normalized_user_name", "display_name", "suspended_at", "deleted_at",
                 })
        {
            yield return new TestCaseData(columnName);
        }
    }

    public static IEnumerable<TestCaseData> CheckConstraintCases()
    {
        yield return new TestCaseData(
            "chk_users_email_not_blank",
            "btrim(email) <> '' AND btrim(normalized_email) <> ''");
        yield return new TestCaseData(
            "chk_users_user_name_pair",
            "(user_name IS NULL AND normalized_user_name IS NULL) OR (user_name IS NOT NULL AND normalized_user_name IS NOT NULL)");
        yield return new TestCaseData(
            "chk_users_security_version_positive",
            "security_version > 0");
        yield return new TestCaseData(
            "chk_users_version_positive",
            "version > 0");
        yield return new TestCaseData(
            "chk_users_status_timestamps",
            "(status <> 'SUSPENDED' OR suspended_at IS NOT NULL) AND (status <> 'DELETED' OR deleted_at IS NOT NULL)");
    }
}